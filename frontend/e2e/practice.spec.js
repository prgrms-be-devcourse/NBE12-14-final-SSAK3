import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'

async function signup(page) {
  await page.goto('/')
  await expect(page.getByText('연습 데모', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '지금 연습 시작하기' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByRole('link', { name: '회원가입', exact: true }).click()
  const suffix = randomUUID().slice(0, 8)
  const email = `demo-${suffix}@example.test`
  await page.getByLabel('닉네임').fill(`데모-${suffix}`)
  await page.getByLabel('이메일').fill(email)
  await page.getByLabel('비밀번호', { exact: true }).fill('Demo-only-123!')
  await page.getByRole('button', { name: '가입하고 연습 시작하기' }).click()
  await expect(page).toHaveURL(/\/practice$/)
  await expect(page.getByRole('button', { name: '연습 시작하기' })).toBeEnabled()
  return email
}

test('real signup, refresh, correct answer, result and wrong retry', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.screenshot({ path: 'test-results/lobby-desktop.png', fullPage: true })
  await signup(page)
  await page.getByRole('button', { name: '운영체제', exact: true }).click()
  await expect(page.getByText('아직 등록된 문제가 없어요.')).toBeVisible()
  await expect(page.getByRole('button', { name: '연습 시작하기' })).toBeDisabled()
  await page.getByRole('button', { name: '네트워크', exact: true }).click()
  await page.getByRole('button', { name: '연습 시작하기' }).click()
  await expect(page.getByRole('heading', { name: 'TCP의 특징으로 알맞은 것은?' })).toBeVisible()
  const firstUrl = page.url()
  const choices = await page.getByRole('group', { name: '답안 보기' }).getByRole('button').allTextContents()
  await expect(page.getByRole('button', { name: '답안 제출', exact: true })).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'TCP의 특징으로 알맞은 것은?' })).toBeVisible()
  expect(await page.getByRole('group', { name: '답안 보기' }).getByRole('button').allTextContents()).toEqual(choices)
  await page.screenshot({ path: 'test-results/question-desktop.png', fullPage: true })
  await page.getByRole('button', { name: /전송 순서를 보장/ }).click()
  await page.getByRole('button', { name: '답안 제출', exact: true }).click()
  await expect(page.getByText('정답이에요!', { exact: true })).toBeVisible()
  await expect(page.getByText(/TCP는 연결 지향 프로토콜로/)).toBeVisible()
  await page.reload()
  await expect(page.getByText('정답이에요!', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '답안 제출', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '결과 확인하기' }).click()
  await expect(page.getByRole('heading', { name: '오늘의 연습을 마쳤어요!' })).toBeVisible()
  await expect(page.locator('.result-stats > div').nth(0)).toHaveText('1정답')
  await page.screenshot({ path: 'test-results/result-desktop.png', fullPage: true })
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '다시 풀기', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'TCP의 특징으로 알맞은 것은?' })).toBeVisible()
  expect(page.url()).not.toEqual(firstUrl)
  await page.getByRole('button', { name: /비연결형 통신/ }).click()
  await page.getByRole('button', { name: '답안 제출', exact: true }).click()
  await expect(page.getByText('아쉽지만, 하나 더 배웠어요.')).toBeVisible()
  await page.getByRole('button', { name: '결과 확인하기' }).click()
  await expect(page.locator('.result-stats > div').nth(1)).toHaveText('1오답')
  expect(errors).toEqual([])
})

test('mobile resume, abandon and expired login', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const email = await signup(page)
  await page.getByRole('button', { name: '연습 시작하기' }).click()
  await expect(page.getByRole('heading', { name: 'TCP의 특징으로 알맞은 것은?' })).toBeVisible()
  const sessionUrl = page.url()
  await page.getByRole('link', { name: '연습 홈', exact: false }).click()
  await page.getByRole('link', { name: '이어서 풀기' }).click()
  await expect(page).toHaveURL(sessionUrl)
  await expect(page.getByRole('heading', { name: 'TCP의 특징으로 알맞은 것은?' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/question-mobile.png', fullPage: true })
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '연습 종료', exact: true }).click()
  await expect(page.getByRole('heading', { name: '연습을 종료했어요' })).toBeVisible()
  await expect(page.locator('.result-stats > div').nth(2)).toHaveText('1미제출')
  await expect(page.getByText(/TCP는 연결 지향 프로토콜로/)).toHaveCount(0)
  await page.evaluate(() => sessionStorage.setItem('csmatch.accessToken', 'expired-demo-token'))
  await page.goto('/practice')
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByText(/로그인이 만료됐어요/)).toBeVisible()
  await page.getByLabel('이메일').fill(email)
  await page.getByLabel('비밀번호', { exact: true }).fill('Demo-only-123!')
  await page.getByRole('button', { name: '로그인', exact: true }).click()
  await expect(page).toHaveURL(/\/practice$/)
  await expect(page.getByRole('button', { name: '연습 시작하기' })).toBeEnabled()
})

test('lost answer response recovers persisted result without resubmission', async ({ page }) => {
  await signup(page)
  await page.getByRole('button', { name: '연습 시작하기' }).click()
  await page.getByRole('button', { name: /전송 순서를 보장/ }).click()
  let submissions = 0
  await page.route('**/practice/sessions/*/answers', async route => {
    submissions++
    await route.fetch()
    await route.abort('failed')
  })
  await page.getByRole('button', { name: '답안 제출', exact: true }).click()
  await expect(page.getByText('정답이에요!', { exact: true })).toBeVisible()
  expect(submissions).toBe(1)
  await expect(page.getByRole('button', { name: '답안 제출', exact: true })).toHaveCount(0)
})
